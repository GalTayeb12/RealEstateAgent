async function generateSample(locale) {
  const isHebrew = locale === "he";
  const data = SAMPLE[locale];
  const strings = L[locale];

  // Brand colours
  const teal   = rgb(0.071, 0.247, 0.251);  // #123F40
  const gold   = rgb(0.784, 0.608, 0.235);  // #C89B3C
  const ivory  = rgb(0.961, 0.941, 0.910);  // #F5F0E8
  const dark   = rgb(0.110, 0.106, 0.098);  // #1C1B19
  const muted  = rgb(0.420, 0.408, 0.376);  // #6B6860
  const border = rgb(0.867, 0.851, 0.831);  // #DDD9D3

  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]);
  const { width, height } = page.getSize();

  const margin  = 60;
  const headerH = 84;
  const footerH = 32;

  // Fonts
  let font, bold;
  if (isHebrew) {
    doc.registerFontkit(fontkit);
    const fontsDir = path.join(root, "public", "fonts");
    const [regBytes, boldBytes] = await Promise.all([
      readFile(path.join(fontsDir, "Heebo-Regular.ttf")),
      readFile(path.join(fontsDir, "Heebo-Bold.ttf")),
    ]);
    font = await doc.embedFont(regBytes);
    bold = await doc.embedFont(boldBytes);
  } else {
    font = await doc.embedFont(StandardFonts.Helvetica);
    bold = await doc.embedFont(StandardFonts.HelveticaBold);
  }

  function drawText(text, x, y, opts = {}) {
    const f   = opts.font  ?? font;
    const sz  = opts.size  ?? 11;
    const col = opts.color ?? dark;
    const rtl = opts.rtl   ?? isHebrew;
    const drawX = rtl ? x - f.widthOfTextAtSize(text, sz) : x;
    page.drawText(String(text), { x: drawX, y, font: f, size: sz, color: col });
  }

  function drawLine(y, color = border, thickness = 0.75) {
    page.drawLine({ start: { x: margin, y }, end: { x: width - margin, y }, thickness, color });
  }

  const labelX = isHebrew ? width - margin       : margin + 4;
  const valueX = isHebrew ? width - margin - 130 : margin + 150;

  function drawRow(label, value, y, opts = {}) {
    drawText(label, labelX, y, { size: 10, color: muted, rtl: isHebrew });
    drawText(value, valueX, y, {
      font:  opts.bold  ? bold : font,
      size:  opts.size  ?? 10,
      color: opts.color ?? dark,
      rtl: isHebrew,
    });
  }

  const dateLocale = isHebrew ? "he-IL" : "en-GB";
  const dateOpts   = { day: "numeric", month: "long", year: "numeric" };
  const dateAccepted = new Date("2026-11-01").toLocaleDateString(dateLocale, dateOpts);
  const generatedAt  = new Date().toLocaleDateString(dateLocale, dateOpts);
  // Standard fonts (English) cannot encode the shekel sign; use "ILS " prefix.
  const priceStr = isHebrew
    ? `\u20AA${data.finalPrice.toLocaleString("he-IL")}`
    : `ILS ${data.finalPrice.toLocaleString("en-GB")}`;

  // Header ivory band
  page.drawRectangle({ x: 0, y: height - headerH, width, height: headerH, color: ivory });

  page.drawText("Haveniq", { x: margin, y: height - 26, font: bold, size: 9, color: teal });
  const pgW = bold.widthOfTextAtSize("1", 9);
  page.drawText("1", { x: width - margin - pgW, y: height - 26, font: bold, size: 9, color: muted });

  const titleX = isHebrew ? width - margin : margin;
  drawText(strings.title, titleX, height - 50, { font: bold, size: 24, color: dark });

  const dateW = font.widthOfTextAtSize(dateAccepted, 10);
  const dateDrawX = isHebrew ? margin : width - margin - dateW;
  page.drawText(dateAccepted, { x: dateDrawX, y: height - 50, font, size: 10, color: muted });

  drawText(strings.subtitle, titleX, height - 70, { size: 11, color: muted });

  let y = height - headerH - 24;

  drawLine(y, gold, 1.5);
  y -= 24;

  // Property section
  const secX = isHebrew ? width - margin : margin;
  drawText(strings.property, secX, y, { font: bold, size: 8, color: teal });
  y -= 20;

  const propertyRows = [
    [strings.unitType, data.unitLabel],
    [strings.project,  data.projectName],
    [strings.location, data.location],
  ];
  for (const [label, value] of propertyRows) {
    page.drawRectangle({ x: margin, y: y - 4, width: width - margin * 2, height: 18, color: ivory, opacity: 0.5 });
    drawRow(label, value, y);
    y -= 18;
  }

  y -= 14;
  drawLine(y, border);
  y -= 24;

  // Deal details
  drawText(strings.deal, secX, y, { font: bold, size: 8, color: teal });
  y -= 20;

  const dealRows = [
    [strings.buyer,     data.buyerEmail,  false],
    [strings.developer, data.companyName, false],
    [strings.price,     priceStr,         true],
    [strings.date,      dateAccepted,     false],
    [strings.ref,       data.offerId,     false],
  ];
  for (const [label, value, isPrice] of dealRows) {
    if (isPrice) {
      page.drawRectangle({ x: margin, y: y - 4, width: width - margin * 2, height: 20, color: ivory });
    }
    drawRow(label, value, y, { bold: isPrice, size: isPrice ? 13 : 10, color: isPrice ? teal : dark });
    y -= isPrice ? 22 : 18;
  }

  y -= 16;
  drawLine(y, border);
  y -= 28;

  // Disclaimer
  for (const line of [strings.disclaimer1, strings.disclaimer2, strings.disclaimer3]) {
    drawText(line, isHebrew ? width - margin : margin, y, { size: 9, color: muted });
    y -= 14;
  }

  // Footer ivory band
  page.drawRectangle({ x: 0, y: 0, width, height: footerH, color: ivory });
  page.drawLine({ start: { x: 0, y: footerH }, end: { x: width, y: footerH }, thickness: 1, color: teal });
  const footerText = `${strings.footer} \u00B7 ${generatedAt}`;
  drawText(footerText, isHebrew ? width - margin : margin, 10, { size: 8, color: muted });

  return doc.save();
}

async function main() {
  await mkdir(path.join(root, "docs/samples"), { recursive: true });
  for (const locale of ["he", "en"]) {
    const bytes = await generateSample(locale);
    const filename = `deal-summary-${locale}.pdf`;
    await writeFile(path.join(root, "docs/samples", filename), Buffer.from(bytes));
    console.log(`Written: docs/samples/${filename}`);
  }
}

main().catch(console.error);
