/**
 * scripts/gen-pdf-samples.mjs
 * Generates two sample Deal Summary PDFs (Hebrew and English).
 * Uses pdf-lib + @pdf-lib/fontkit for Heebo embedding.
 * Run: node scripts/gen-pdf-samples.mjs
 */
